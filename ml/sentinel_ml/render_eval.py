"""Render docs/EVALUATION.md from a saved ``metrics.json``. No number in the report is typed by hand."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

from sentinel_core.attribution.model import CLASSES

NH = "needs_human"


def pct(d: dict[str, Any] | None, digits: int = 1) -> str:
    if not d or d.get("rate") is None:
        return "n/a"
    lo, hi = d["ci95"]
    return (
        f"{100 * d['rate']:.{digits}f}% ({d['k']}/{d['n']}; 95% CI {100 * lo:.0f}-{100 * hi:.0f}%)"
    )


def f(x: float | None, nd: int = 2) -> str:
    return "n/a" if x is None else f"{x:.{nd}f}"


def table(headers: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


def render_smap(m: dict[str, Any]) -> str:
    """The real-data section: L1 event-level results on the labeled SMAP/MSL anomalies."""
    varying, const = m["varying_train_channels"], m["constant_train_channels"]

    def row(name: str, d: dict[str, Any]) -> list[str]:
        return [
            name,
            str(d["channels"]),
            str(d["true_events"]),
            f(d["precision"]),
            f(d["recall"]),
            f(d["f1"]),
            f"{d['tp']}/{d['fp']}/{d['fn']}",
        ]

    stat = ", ".join(
        f"{k}: {v}" for k, v in sorted(m["all"]["events_detected_by_statistic"].items())
    )
    intro = (
        "This is the only part of the report measured on **real spacecraft telemetry**. The L1 "
        "statistical detector is calibrated on each channel's train array and scored on its test array "
        "against the labeled anomaly sequences (Hundman et al., KDD 2018) with event-level rules: a "
        "labeled sequence is detected if any predicted run overlaps it, and a predicted run overlapping "
        "no sequence is a false positive. `T-10` (no label row) is excluded and `P-2` uses the union of "
        f"its two label rows, so there are {m['all']['true_events']} labeled events. Only L1 applies: "
        "channel IDs are anonymized, so the redundancy, protocol and space-weather layers have nothing "
        "to work with, and the LSTM forecaster (L2) is **not built yet**.\n"
    )
    headers = ["subset", "channels", "events", "precision", "recall", "F1", "TP/FP/FN"]
    rows = [
        row("all labeled channels", m["all"]),
        row("SMAP", m["SMAP"]),
        row("MSL", m["MSL"]),
        row("channels with a varying training signal", varying),
        row("channels with a constant training signal", const),
    ]
    note = (
        f"**Read the varying-signal row as the honest number** (F1 {f(varying['f1'])}). The "
        f"{const['channels']} constant-training channels score {f(const['f1'])} almost trivially: any "
        "departure from a constant is out of range, so a range check alone finds it. Events found by "
        f"each statistic (one event can be found by several): {stat}. There is no comparison to "
        "published results here: those use different scoring conventions, and this detector was not "
        "tuned on this data.\n"
    )
    return "\n".join(
        [
            "## Real data: L1 on SMAP/MSL anomalies (event level)\n",
            intro,
            table(headers, rows) + "\n",
            note,
        ]
    )


def render(m: dict[str, Any], smap: dict[str, Any] | None = None) -> str:
    meta, w = m["meta"], m["windows"]
    lines: list[str] = []
    add = lines.append

    add("# Evaluation\n")
    add(
        "> Generated by `python -m sentinel_ml.render_eval` from `docs/data/evaluation_v1.json`. "
        "Every number below comes from that file, which comes from a real run "
        f"(commit `{meta['git_sha'][:10]}`, model `{meta['model_version']}`). Nothing is typed in by hand.\n"
    )
    add("## What is (and is not) being measured\n")
    add(
        "All attack and fault scenarios are **synthetic**: they are injected into a simulated spacecraft bus "
        "(driven by real PCoE battery and IMS bearing trajectories) and a real-data replay path. Training and "
        "test scenarios come from the **same simulator**, so these results measure how well the platform "
        "separates the simulator's scenario families, *not* accuracy on a real spacecraft. See "
        "[LIMITATIONS](LIMITATIONS.md).\n"
    )
    nw = meta["n_windows"]
    add(
        f"- **Runs:** {meta['n_runs']} (33 scenarios x 14 seeded variants; variants shift timing and scale "
        "magnitudes and change all noise). Each run is 1,800 simulated minutes.\n"
        f"- **Splits (by variant index):** train {meta['splits']['train']}, validation {meta['splits']['val']}, "
        f"test {meta['splits']['test']}. Every scenario appears in every split with different seeds. "
        f"Incident windows: train {nw['train']}, validation {nw['val']}, test {nw['test']}.\n"
        f"- **Model:** multinomial logistic regression (C={meta['model']['c']}, temperature "
        f"{meta['model']['temperature']:.2f}); abstention thresholds tau={meta['model']['tau']:.2f}, "
        f"delta={meta['model']['delta']:.2f}, tuned on validation only to reach >= 90% answered accuracy at "
        "maximum coverage. The test split was scored once, after all design iteration on validation.\n"
        f"- **Real inputs used:** {', '.join(meta['data_sources'])} trajectories; space weather from real DONKI "
        f"data (context per run: {meta['weather_context']}).\n"
        "- **Caveat on the intervals:** windows from the same scenario are not independent (4 test seeds per "
        "scenario), so the 95% Wilson intervals are optimistic. Treat differences of a few points as noise.\n"
    )

    add("## Headline (test split, incident-window level)\n")
    rows = [
        ["Forced-choice accuracy (never abstains)", pct(w["forced_choice_accuracy"])],
        ["Accuracy on the windows it chooses to answer", pct(w["answered_accuracy"])],
        ["Coverage (fraction answered)", pct(w["coverage"])],
        ["Strict accuracy (an abstention counts as wrong)", pct(w["strict_accuracy"])],
        [
            "When the top class was wrong, the platform abstained",
            pct(w["abstain_when_it_would_have_been_wrong"]),
        ],
    ]
    add(table(["Metric", "Value"], rows) + "\n")
    b = m["baselines"]
    add(
        f"For reference: always answering the majority class (`{b['majority_class']['class']}`) scores "
        f"{pct(b['majority_class']['accuracy'])}; a transparent hand-written rule set scores "
        f"{pct(b['hand_rules']['strict_accuracy'])} strict.\n"
    )

    conf = w["confusion"]
    inc = [c for c in CLASSES if c != "nominal"]
    inc_n = sum(sum(conf[c].values()) for c in inc)
    inc_ok = sum(conf[c][c] for c in inc)
    inc_nh = sum(conf[c][NH] for c in inc)
    inc_wrong = inc_n - inc_ok - inc_nh
    add(
        f"Looking only at windows that overlap a real fault or attack ({inc_n} windows): "
        f"**{inc_ok} correct, {inc_nh} handed to a human, {inc_wrong} confidently wrong.**\n"
    )

    add("## Confusion matrix (rows: truth, columns: platform verdict)\n")
    cols = [*CLASSES, NH]
    add(
        table(["truth \\ verdict", *cols], [[c, *[str(conf[c][k]) for k in cols]] for c in CLASSES])
        + "\n"
    )
    nom_win = sum(conf["nominal"].values())
    add(
        f"`nominal` rows are incident windows that do **not** overlap any injected fault: spurious alarms "
        f"({nom_win} windows). Most of them end as `{NH}` rather than `nominal`, because a weak, brief window "
        "sits close to the weak-evidence `mechanical_failure` class and the abstention margin is strict.\n"
    )

    add("## Per-class metrics (an abstention counts as a miss)\n")
    pc = w["per_class"]
    add(
        table(
            ["class", "precision", "recall", "F1", "windows"],
            [
                [
                    c,
                    f(pc[c]["precision"]),
                    f(pc[c]["recall"]),
                    f(pc[c]["f1"]),
                    str(pc[c]["support"]),
                ]
                for c in CLASSES
            ],
        )
        + "\n"
    )

    add("## Detection and time-to-detect per scenario (test variants)\n")
    add(
        "Time to detect is the median number of simulated minutes from the true start of the fault/attack to "
        "the first fired detector output. `verdicts` counts the platform's verdict on each incident window "
        "overlapping the fault.\n"
    )
    rows = []
    for r in m["scenarios"]:
        if r["truth"] == "nominal":
            continue
        det = r["detected"]
        rows.append(
            [
                f"`{r['scenario']}`",
                r["truth"],
                f"{det['k']}/{det['n']}",
                f(r["median_time_to_detect_min"], 1),
                ", ".join(f"{k}: {v}" for k, v in sorted(r["verdicts"].items())) or "-",
            ]
        )
    add(table(["scenario", "truth", "detected", "median TTD (min)", "verdicts"], rows) + "\n")

    add("## The hard confusable pairs\n")
    add(
        "The pairs the platform exists for. `correct` = windows given the right class; `abstained` = "
        "`needs_human`; `as partner` = confidently labeled as the *partner's* (different) class.\n"
    )
    rows = []
    for h in m["hard_pairs"]:
        a, p = h["pair"]
        cells = []
        for n in (a, p):
            d = h[n]
            cells.append(
                f"{d['correct']['k']}/{d['correct']['n']} correct, {d['abstained']} abstained, "
                f"{d['confused_as_partner_class']} as partner"
            )
        rows.append(
            [f"`{a}` vs `{p}`", f"{h['classes'][0]} / {h['classes'][1]}", cells[0], cells[1]]
        )
    add(table(["pair", "classes", "first", "second"], rows) + "\n")

    fa = m["false_alarms"]
    add("## False alarms\n")
    add(
        f"On {fa['nominal_runs']} nominal test runs ({fa['simulated_days']:.1f} simulated days) the detectors "
        f"opened **{fa['false_incident_windows']} incident windows ({f(fa['false_windows_per_day'])} per "
        f"simulated day)**. Attribution labeled {pct(fa['false_windows_classified_nominal_by_attribution'])} "
        f"of them `nominal`; {fa['false_windows_that_reach_operators']} would reach an operator. "
        f"A further {fa['windows_outside_the_fault_in_fault_runs']} windows opened outside the injected fault "
        "in fault runs (including ones caused by the fault's aftermath).\n"
    )

    add("## Which layers matter (ablation: features of one layer zeroed, model retrained)\n")
    rows = [
        [a["config"], pct(a["forced_choice_accuracy"]), pct(a["strict_accuracy"])]
        for a in m["ablations"]
    ]
    add(table(["configuration", "forced-choice accuracy", "strict accuracy"], rows) + "\n")

    add("## Generalization to unseen scenario types (leave-one-scenario-out)\n")
    loso = m["leave_one_scenario_out"]
    good = [r for r in loso if r["correct"]["rate"] is not None and r["correct"]["rate"] >= 0.75]
    zero = [r for r in loso if r["correct"]["k"] == 0]
    add(
        f"Training on every scenario **except** one, then classifying the held-out one: "
        f"{len(good)} of {len(loso)} scenarios are still classified correctly at >= 75%, and "
        f"{len(zero)} are never classified correctly "
        f"({', '.join('`' + r['scenario'] + '`' for r in zero)}). "
        "The learned model recognizes *families it has seen*; it does not reason its way to a new failure "
        f"mode. The ones that do generalize: {', '.join('`' + r['scenario'] + '`' for r in good)}.\n"
    )

    add("## Failure cases (window accuracy <= 50%)\n")
    rows = []
    for r in m["scenarios"]:
        wa = r["window_accuracy"]
        if wa is not None and wa <= 0.5:
            rows.append(
                [
                    f"`{r['scenario']}`",
                    r["truth"],
                    f(wa),
                    ", ".join(f"{k}: {v}" for k, v in sorted(r["verdicts"].items())),
                ]
            )
    add(table(["scenario", "truth", "window accuracy", "verdicts"], rows) + "\n")
    add(
        "These are mainly the slow, in-limits, single-sensor cases (`manip_*`, `spoof_*`, "
        "`sensor_drift_battv`) and slow degradation. Their evidence is one sensor departing gradually from another, and the platform's "
        "features cannot tell an attacker's clean synthetic values, a drifting sensor and a low-and-slow "
        "manipulation apart. **The correct behavior is to say so**: most such windows end as "
        f"`{NH}` rather than a confident wrong class. That is a limitation of the evidence, not a solved "
        "problem.\n"
    )

    if smap is not None:
        add(render_smap(smap))

    add("## Reproduce\n")
    add(
        "```bash\n"
        "python scripts/tasks.py data                 # real datasets (DONKI needs a cached window)\n"
        "uv run python -m sentinel_ml.make_dataset    # 462 scenario runs -> data/processed/records.pkl (~7 min)\n"
        "uv run python -m sentinel_ml.evaluate --out ml/runs/attribution-v1\n"
        "uv run python -m sentinel_ml.smap_eval       # real SMAP/MSL, L1, event level (~10 s)\n"
        "uv run python -m sentinel_ml.render_eval --metrics ml/runs/attribution-v1/metrics.json\n"
        "```\n"
    )
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--metrics", type=Path, default=Path("ml/runs/attribution-v1/metrics.json"))
    ap.add_argument("--smap", type=Path, default=Path("docs/data/smap_msl_l1_v1.json"))
    ap.add_argument("--out", type=Path, default=Path("docs/EVALUATION.md"))
    args = ap.parse_args()
    smap = json.loads(args.smap.read_text(encoding="utf-8")) if args.smap.is_file() else None
    args.out.write_text(
        render(json.loads(args.metrics.read_text(encoding="utf-8")), smap), encoding="utf-8"
    )
    print("wrote", args.out)


if __name__ == "__main__":
    main()
